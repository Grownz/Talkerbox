fn main() {
    // Re-copy the externalBin sidecar into target/ when it is replaced.
    println!("cargo:rerun-if-changed=binaries");
    println!("cargo:rerun-if-changed=vosk");
    // Vosk (speech input): link against the import library in vosk/ (made by vosk/setup.ps1). The DLL is
    // delay-loaded, so the app and test binaries start without it; stt.rs checks for it before first use.
    let vosk = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("vosk");
    println!("cargo:rustc-link-search=native={}", vosk.display());
    println!("cargo:rustc-link-arg=/DELAYLOAD:libvosk.dll");
    println!("cargo:rustc-link-lib=delayimp");
    // Dev runs load the DLLs from next to the exe (target/<profile>); release bundles them as resources.
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    if let Some(profile_dir) = out.ancestors().nth(3) {
        for e in std::fs::read_dir(&vosk).into_iter().flatten().flatten() {
            let p = e.path();
            if p.extension().is_some_and(|x| x == "dll") {
                let _ = std::fs::copy(&p, profile_dir.join(e.file_name()));
            }
        }
    }
    // App command permissions (see app/README.md, Window permissions). With an app manifest every app command is
    // checked against the capabilities; the list comes from `generate_handler!` in lib.rs so it cannot drift.
    let commands = handler_commands(&std::fs::read_to_string("src/lib.rs").expect("read src/lib.rs"));
    println!("cargo:rerun-if-changed=src/lib.rs");
    write_main_window_set(&commands);
    let commands: &'static [&'static str] = Vec::leak(commands.into_iter().map(|c| &*String::leak(c)).collect());
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(commands)))
        .expect("tauri build")
}

/// Command names (last path segment) listed in `tauri::generate_handler![...]`.
fn handler_commands(lib_rs: &str) -> Vec<String> {
    let start = lib_rs.find("generate_handler![").expect("generate_handler! not found in src/lib.rs") + "generate_handler![".len();
    let body = &lib_rs[start..start + lib_rs[start..].find(']').expect("unterminated generate_handler!")];
    let cmds: Vec<String> = body.split(',').map(|s| s.trim().rsplit("::").next().unwrap().to_string()).filter(|s| !s.is_empty()).collect();
    assert!(cmds.iter().all(|c| c.chars().all(|ch| ch.is_ascii_alphanumeric() || ch == '_')), "unexpected generate_handler! entry: {cmds:?}");
    cmds
}

/// `permissions/main-window.toml`: the set of every app command, granted to the main window only.
fn write_main_window_set(commands: &[String]) {
    let list = commands.iter().map(|c| format!("  \"allow-{}\",\n", c.replace('_', "-"))).collect::<String>();
    let toml = format!(
        "# Generated by build.rs from generate_handler! in src/lib.rs - do not edit.\n\n[[set]]\nidentifier = \"main-window\"\n\
         description = \"Every app command; granted to the main window only.\"\npermissions = [\n{list}]\n"
    );
    let path = std::path::Path::new("permissions/main-window.toml");
    // Rewriting an unchanged file would retrigger the build (tauri-build watches permissions/).
    if std::fs::read_to_string(path).ok().as_deref() != Some(toml.as_str()) {
        std::fs::create_dir_all("permissions").unwrap();
        std::fs::write(path, toml).expect("write permissions/main-window.toml");
    }
}
